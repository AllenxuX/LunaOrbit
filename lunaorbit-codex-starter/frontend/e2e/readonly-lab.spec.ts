import { expect, test } from '@playwright/test'

test.skip(process.env.LUNAORBIT_LAB_E2E !== '1', 'Requires the explicit isolated Minikube console tunnel')
test.use({ baseURL: 'http://127.0.0.1:8088' })
test.beforeEach(async ({ request }) => {
  const runtime = await (await request.get('/api/runtime')).json()
  test.skip(runtime.mode !== 'readonly-lab', 'Requires the explicitly read-only deployment')
})

test('actual lab console reads Kafka and discovers MM2 without enabling mutations', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/kafka/clusters')
  await expect(page.locator('.environment-badge')).toHaveText('实验环境 · 只读')
  await expect(page.getByRole('button', { name: '新增 Kafka 集群' })).toBeEnabled()
  expect((await (await page.request.get('/api/runtime')).json()).write_enabled).toBe(false)
  // A fresh user's ordinary page visit must initialize the known lab catalog;
  // creating registrations only in the test owner's API context missed this bug.
  await expect(page.locator('.data-table')).toContainText('实验源集群')
  await expect(page.locator('.data-table')).toContainText('实验目标集群')
  const clusterRows = await (await page.request.get('/api/v1/kafka/clusters')).json()
  expect(clusterRows.total).toBe(2)
  const registrations = ['source', 'target'].map(alias => clusterRows.items.find((item: { bootstrap_servers: string[] }) =>
    item.bootstrap_servers.includes(`kafka-${alias}.lunaorbit-integration.svc.cluster.local:9092`)))
  expect(registrations.every(Boolean)).toBe(true)
  expect((await page.request.post('/api/v1/lab/registrations', { data: {} })).status()).toBe(200)
  expect((await (await page.request.get('/api/v1/kafka/clusters')).json()).total).toBe(2)
  expect(clusterRows.items.filter((item: { status: string }) => item.status === 'connected')).toHaveLength(2)
  expect(new Set(clusterRows.items.map((item: { discovered_cluster_id: string }) => item.discovered_cluster_id)).size).toBe(2)
  await page.goto(`/kafka/clusters/${registrations[0]!.id}/details`)
  await page.getByRole('button', { name: 'lunaorbit-lab-events', exact: true }).click()
  await expect(page.getByRole('heading', { name: /lunaorbit-lab-events 分区/ })).toContainText('RF 1')
  const topics = await (await page.request.get(`/api/v1/kafka/clusters/${registrations[0]!.id}/topics`)).json()
  expect(topics.synthetic).toBe(false)
  expect(topics.items.find((item: { name: string }) => item.name === 'lunaorbit-lab-events').rf_min).toBe(1)
  await expect(page.locator('.demo-settings')).toHaveCount(0)
  await page.screenshot({ path: 'test-results/console-lab-kafka-details.png', fullPage: true })
  await page.goto('/topology')
  await expect(page.locator('[data-discover]')).toBeEnabled()
  await page.locator('[data-discover]').click()
  await expect(page.locator('[data-link]').first()).toBeVisible()
  let snapshot = await (await page.request.get('/api/v1/discovery/scopes/readonly-lab/snapshot?page_size=100')).json()
  expect(snapshot.snapshot.synthetic).toBe(false)
  const forward = snapshot.snapshot.links.find((link: { source_alias: string; target_alias: string }) => link.source_alias === 'source' && link.target_alias === 'target')
  expect(forward.declared).toBe(true)
  expect(forward.observed).toBe(true)
  expect(forward.verified).toBe(false)
  for (const [index, alias] of ['source', 'target'].entries()) {
    expect((await page.request.put('/api/v1/discovery/scopes/readonly-lab/bindings', { data: {
      namespace: forward.namespace, workload_uid: forward.workload_uid, alias, registration_id: registrations[index]!.id,
    } })).status()).toBe(200)
  }
  await expect(async () => {
    expect((await page.request.post('/api/v1/discovery/scopes/readonly-lab/runs', { data: {} })).status()).toBe(202)
  }).toPass({ timeout: 6000, intervals: [2100] })
  await expect(async () => {
    const job = await (await page.request.get('/api/v1/discovery/scopes/readonly-lab/runs/latest')).json()
    expect(job.status).toBe('done')
  }).toPass()
  await page.getByRole('button', { name: /重新加载视图/ }).click()
  await expect(page.locator('.x6-node').first()).toBeVisible()
  await page.getByRole('button', { name: '适应画布', exact: true }).click()
  await page.locator('[data-link]').filter({ hasText: '实验源集群 → 实验目标集群' }).click()
  await expect(page.locator('.evidence-panel')).toContainText('人工确认映射')
  await expect(page.getByRole('region', { name: '查询与潜在影响' })).toHaveCount(0)
  await page.setViewportSize({ width: 1500, height: 1000 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/console-lab-topology.png', fullPage: true })
  snapshot = await (await page.request.get('/api/v1/discovery/scopes/readonly-lab/snapshot?page_size=100')).json()
  expect(snapshot.snapshot.links.every((link: { verified: boolean }) => !link.verified)).toBe(true)
  await page.goto('/kafka/clusters')
  await expect(page.locator('.data-table')).toContainText('连接正常')
  await page.screenshot({ path: 'test-results/console-lab-clusters.png', fullPage: true })
  await page.goto('/')
  await expect(page.locator('[data-registered-total]')).toHaveText('2')
  await expect(page.locator('[data-link-total]')).not.toHaveText('未知')
  await page.screenshot({ path: 'test-results/console-lab-overview.png', fullPage: true })
  await page.goto('/changes')
  await expect(page.locator('[data-change-form]')).toHaveCount(0)
  await expect(page.getByText('当前运行模式未启用变更模拟', { exact: false })).toBeVisible()
  await page.goto('/security')
  await expect(page.locator('[data-login]')).toBeVisible()
  await expect(page.locator('[data-inbox]')).toHaveCount(0)
  await expect(page.locator('[data-acl-request]')).toHaveCount(0)
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(errors).toEqual([])
  // Retain this browser's synthetic registrations for the session, never real assets.
})

test('console navigation works at mobile width without horizontal document overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const menu = page.getByRole('button', { name: '打开导航菜单', exact: true })
  await expect(menu).toBeVisible()
  await menu.click()
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('navigation', { name: '主导航', exact: true }).getByRole('link', { name: 'Kafka 集群' }).click()
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('#admin-sidebar')).not.toBeInViewport()
  await expect(page.getByRole('heading', { name: 'Kafka 集群管理', exact: true })).toBeVisible()
  await expect(page.locator('.data-table')).toContainText('实验源集群')
  await expect(page.locator('.data-table')).toContainText('实验目标集群')
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)
  expect(overflow).toBe(false)
  await page.screenshot({ path: 'test-results/console-lab-mobile.png', fullPage: true })
})
