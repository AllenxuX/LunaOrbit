import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, expect, it, vi } from 'vitest'
import Clusters from './Clusters.vue'

afterEach(() => { vi.unstubAllGlobals(); sessionStorage.clear() })
const cluster = { id: 'synthetic-1', revision: 1, display_name: 'Synthetic cluster', bootstrap_servers: ['broker.example.test:9093'], enabled: true, security_protocol: 'SASL_SSL', sasl_mechanism: 'PLAIN', status: 'unverified', version_reported: '3.7', version_source: 'manual', capabilities: [], credentials_configured: true }
function setup() {
  vi.stubGlobal('fetch', vi.fn(async (url: string) => new Response(JSON.stringify(url.endsWith('/session') ? { user_id: 'synthetic', mode: 'mock', persistent: false } : { items: [cluster], total: 1, page: 1, page_size: 20 }))))
  return mount(Clusters)
}
it('shows mock list and stores only active registration ID in this browser session', async () => {
  const wrapper = setup(); await flushPromises()
  expect(wrapper.text()).toContain('Mock')
  expect(wrapper.text()).toContain('Synthetic cluster')
  await wrapper.get('[data-action="switch"]').trigger('click')
  expect(sessionStorage.getItem('lunaorbit.activeClusterId')).toBe('synthetic-1')
  expect(sessionStorage.length).toBe(1)
  wrapper.unmount()
})
it('keeps editing secrets empty and erases them when cancelled', async () => {
  const wrapper = setup(); await flushPromises()
  await wrapper.get('[data-action="edit"]').trigger('click')
  expect((wrapper.get('input[name="password"]').element as HTMLInputElement).value).toBe('')
  await wrapper.get('input[name="password"]').setValue('synthetic-write-only')
  await wrapper.get('[data-action="cancel"]').trigger('click')
  await wrapper.get('[data-action="edit"]').trigger('click')
  expect((wrapper.get('input[name="password"]').element as HTMLInputElement).value).toBe('')
  expect(JSON.stringify({ ...sessionStorage })).not.toContain('synthetic-write-only')
  wrapper.unmount()
})
it('creates a registration with write-only secrets then removes the form', async () => {
  const wrapper = setup(); await flushPromises()
  await wrapper.findAll('button').find(b => b.text() === '新增 Kafka 集群')!.trigger('click')
  const dialog = wrapper.get('[role="dialog"]')
  await dialog.findAll('input')[0]!.setValue('Synthetic new')
  await dialog.findAll('textarea')[1]!.setValue('broker.example.test:9093')
  await dialog.get('input[name="username"]').setValue('synthetic-user')
  await dialog.get('input[name="password"]').setValue('synthetic-write-only')
  await dialog.get('form').trigger('submit'); await flushPromises()
  expect(wrapper.find('[role="dialog"]').exists()).toBe(false)
  expect(wrapper.text()).toContain('集群配置已保存')
  expect(sessionStorage.length).toBe(0)
  wrapper.unmount()
})
it('starts asynchronous mock probe and polls before refreshing results', async () => {
  const wrapper = setup(); await flushPromises()
  const fetcher = vi.mocked(fetch)
  fetcher.mockImplementation(async (input, options) => new Response(JSON.stringify(String(input).endsWith('/probe') ? options?.method === 'POST' ? { job_id: 'synthetic-job', status: 'pending' } : { job_id: 'synthetic-job', status: 'done', error_code: 'authentication_failed' } : { items: [cluster], total: 1 })))
  await wrapper.findAll('button').find(b => b.text() === '模拟连接测试')!.trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('Mock：认证失败')
  const probeCalls = fetcher.mock.calls.filter(c => String(c[0]).endsWith('/probe'))
  expect(probeCalls.map(c => c[1]?.method)).toEqual(['POST', 'GET'])
  wrapper.unmount()
})
it('disables a registration and requires confirmation before soft deletion', async () => {
  const wrapper = setup(); await flushPromises()
  const fetcher = vi.mocked(fetch)
  await wrapper.findAll('button').find(b => b.text() === '停用')!.trigger('click'); await flushPromises()
  expect(fetcher.mock.calls.some(c => c[1]?.method === 'PATCH' && JSON.parse(c[1]?.body as string).enabled === false)).toBe(true)
  await wrapper.findAll('button').find(b => b.text() === '删除')!.trigger('click')
  expect(fetcher.mock.calls.some(c => c[1]?.method === 'DELETE')).toBe(false)
  await wrapper.findAll('button').find(b => b.text() === '移除集群')!.trigger('click'); await flushPromises()
  expect(fetcher.mock.calls.some(c => c[1]?.method === 'DELETE')).toBe(true)
  wrapper.unmount()
})
it('clears submitted credentials even when the server rejects the update safely', async () => {
  const wrapper = setup(); await flushPromises()
  await wrapper.get('[data-action="edit"]').trigger('click')
  await wrapper.get('input[name="password"]').setValue('synthetic-write-only')
  vi.mocked(fetch).mockResolvedValue(new Response(JSON.stringify({ error: { message: 'private-server-detail' } }), { status: 500 }))
  await wrapper.get('[role="dialog"] form').trigger('submit'); await flushPromises()
  expect((wrapper.get('input[name="password"]').element as HTMLInputElement).value).toBe('')
  expect(wrapper.text()).toContain('操作失败，请稍后重试')
  expect(wrapper.text()).not.toContain('private-server-detail')
  wrapper.unmount()
})
it('shows plaintext risk and supports both SCRAM mechanisms without a JAAS input', async () => {
  const wrapper = setup(); await flushPromises()
  await wrapper.get('[data-action="edit"]').trigger('click')
  const selects = wrapper.get('[role="dialog"]').findAll('select')
  await selects[0]!.setValue('SASL_PLAINTEXT')
  expect(wrapper.text()).toContain('不加密网络流量')
  expect(selects[1]!.text()).toContain('SCRAM-SHA-256')
  expect(selects[1]!.text()).toContain('SCRAM-SHA-512')
  expect(wrapper.find('input[name="jaas"]').exists()).toBe(false)
  wrapper.unmount()
})
